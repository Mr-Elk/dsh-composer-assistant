export const MESSAGES: Record<UiLocale, Record<MessageKey, string>> = { zh, en }

export const MESSAGE_KEYS = Object.keys(zh) as MessageKey[]

/** Temporary switch: the language selector stays hidden until all copy is translated. */
export const LANGUAGE_SELECTION_ENABLED = true

/** The language used by the UI; while the selector is off, always follow DSH. */
export function effectiveLanguage(language: 'follow' | 'zh' | 'en'): 'follow' | 'zh' | 'en' {
  return LANGUAGE_SELECTION_ENABLED ? language : 'follow'
}

/** Resolve the UI locale from the setting and DSH's locale. */
export function resolveUiLocale(language: 'follow' | 'zh' | 'en', dshLocale?: string | null): UiLocale {
  if (language === 'zh' || language === 'en') return language
  return typeof dshLocale === 'string' && dshLocale.toLowerCase().startsWith('en') ? 'en' : 'zh'
}

/** Translate one key; `{name}` placeholders are replaced from vars. */
export function t(locale: UiLocale, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = MESSAGES[locale][key]
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match))
}
